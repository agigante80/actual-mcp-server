const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const WORKFLOW = join(ROOT, '.github', 'workflows', 'dependency-update.yml');
const CICD_WORKFLOW = join(ROOT, '.github', 'workflows', 'ci-cd.yml');

let passed = 0;
let failed = 0;
function check(label, fn) {
  try { fn(); console.log(`  ok: ${label}`); passed++; }
  catch (err) { console.error(`  FAIL: ${label} -> ${err.message}`); failed++; }
}

// Split a workflow into step blocks: each block starts at a "- name:" line.
// Text before the first step (triggers, permissions) is dropped.
function stepBlocks(text) {
  const parts = text.split(/\n(?=\s+- name: )/);
  return parts.filter((p) => /^\s+- name: /.test(p) || /(^|\n)\s+- name: /.test(p)).slice(0);
}

// (a) App token generated before any checkout; every checkout uses it AND
// carries an explicit `persist-credentials: true` (#262): the persisted App
// credential is what authenticates the later pushes to main, so disabling
// persistence (in any YAML spelling) breaks the release exactly like a
// missing `token:`, and relying on the upstream default is pin-fragile.
// Comment lines are stripped before matching so prose ABOUT the setting can
// neither satisfy nor trip the detector.
function withoutComments(block) {
  return block.split('\n').filter((l) => !/^\s*#/.test(l)).join('\n');
}

// #325: invariant (a) is scoped to ONE job, not the whole file.
//
// The reporter job (report-train-failure) checks out deliberately WITHOUT the
// App token and with persist-credentials: false, because it holds issues: write
// and must never have the installation credential on disk. Evaluating (a) over
// the whole file would turn it red and push an implementer toward the one repair
// the design forbids: handing the reporter the App token. The rescope is
// NARROWING ONLY. Inside update-test-release every original requirement (the
// token, the explicit pin, the rejection of `false` in all five spellings, #262)
// still applies, and NEGATIVE (a) proves it.
// Every job whose body actually pushes. Behaviour, not naming: this is what
// invariant (a) genuinely protects (the persisted App credential authenticates
// the pushes), so it selects update-test-release today and would pick up any
// future pushing job without anyone remembering to update a name list.
//
// A name-based narrowing would have silently exempted such a job, which is the
// cost the #325 reporter split would otherwise have imposed. The heuristic is
// the literal `git push origin`; a job pushing by some other spelling escapes it.
function pushingJobs(text) {
  const names = [...text.matchAll(/^  ([A-Za-z0-9_-]+):\s*$/gm)].map((m) => m[1]);
  return names.map((nm) => jobSection(text, nm)).filter((j) => /git push origin/.test(withoutComments(j)));
}

function jobSection(text, jobName) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => new RegExp(`^  ${jobName}:\\s*$`).test(l));
  if (start === -1) return '';
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i += 1) {
    if (/^  [A-Za-z0-9_-]+:\s*$/.test(lines[i])) { end = i; break; }
  }
  return lines.slice(start, end).join('\n');
}
function appTokenAuthenticatesEveryCheckout(text) {
  const blocks = stepBlocks(text);
  const tokenIdx = blocks.findIndex((b) => b.includes('create-github-app-token'));
  const checkouts = blocks
    .map((b, i) => ({ b: withoutComments(b), i }))
    .filter(({ b }) => b.includes('uses: actions/checkout@'));
  if (tokenIdx === -1 || checkouts.length === 0) return false;
  return checkouts.every(({ b, i }) =>
    i > tokenIdx &&
    b.includes('token: ${{ steps.token.outputs.token }}') &&
    /persist-credentials:\s*['"]?true\b/i.test(b) &&
    !/persist-credentials:\s*['"]?false\b/i.test(b));
}

// (b) Token-in-URL auth writes the secret into .git/config; banned.
function hasTokenInUrlAuth(text) {
  return text.includes('x-access-token:');
}

// (c) The bump step must resync the lockfile after bumping and before committing.
function bumpResyncsLockfile(text) {
  const bumpStep = stepBlocks(text).find((b) => b.includes('npm run version:bump'));
  if (!bumpStep) return false;
  const bump = bumpStep.indexOf('npm run version:bump');
  const resync = bumpStep.indexOf('npm install --package-lock-only');
  const commit = bumpStep.indexOf('git commit');
  return resync > bump && commit > resync;
}

// (d) The `} || {` compound guard suppresses errexit inside the left group and
// produced the false "Develop fast-forwarded" success in run 28632676467.
function hasCompoundGuardPattern(text) {
  return /\}\s*\|\|\s*\{/.test(text);
}

// (e) #301: EXACTLY ONE workflow may create the GitHub Release for a v* tag, and
// it must be ci-cd.yml.
//
// History: this invariant used to require the release action to sit AFTER
// `gh run watch` inside dependency-update.yml, because that lane created its own
// Release and the watch step was what stopped it publishing ahead of CI. Two
// workflows calling softprops/action-gh-release on one tag meant the surviving
// BODY was decided by write order (the action upserts by tag), which is
// ordering-dependent rather than designed.
//
// The ownership rule that replaces it is strictly stronger. ci-cd.yml's release
// job is tag-gated and `needs:` every verification job, so it structurally cannot
// publish for a tag whose pipeline is not green: sequencing is enforced by the
// job graph rather than by step order inside one lane. Anchored on the action's
// `uses:` line, so renaming steps or jobs cannot evade it.
const RELEASE_ACTION = 'uses: softprops/action-gh-release';
const RELEASE_OWNER = 'ci-cd.yml';
function workflowsCreatingRelease(root) {
  const dir = join(root, '.github', 'workflows');
  return readdirSync(dir)
    .filter((f) => f.endsWith('.yml') || f.endsWith('.yaml'))
    .filter((f) => withoutComments(readFileSync(join(dir, f), 'utf8')).includes(RELEASE_ACTION));
}
// The dependency lane keeps watching the publish pipeline even though it no
// longer publishes: `--exit-status` is what makes a failed release train fail
// this job loudly instead of passing silently.
function watchesPublishPipeline(text) {
  return /gh run watch\b[^\n]*--exit-status/.test(text);
}

// (f) A hardcoded tool count (the "62 MCP tools" drift) is banned, and the file
// that OWNS the release body must interpolate a computed count.
//
// #301 moved this from dependency-update.yml to ci-cd.yml along with the body
// itself, and widened the literal ban to BOTH files. That widening immediately
// caught a real stale literal in ci-cd.yml's Docker E2E summary, which had read
// "all 62 tools" since well before the count reached 71: the original invariant
// only ever looked at the other file.
// Comment lines are stripped before matching, mirroring invariants (a) and (l):
// both workflows now carry comments that quote the banned literal ("all 62
// tools") as the counter-example being guarded against, and prose ABOUT the rule
// must neither satisfy nor trip the detector.
function hardcodedToolCount(text) {
  return /\b\d+\s+(MCP\s+)?tools\b/i.test(withoutComments(text));
}
function computesToolCount(text) {
  return text.includes('steps.facts.outputs.tool_count');
}
// The migrated companion fact: the release body names the pinned upstream API
// version, derived from the tagged tree rather than passed between workflows.
function computesApiVersion(text) {
  return text.includes('steps.facts.outputs.api_version');
}

// (g) Behavioral lock agreement: catches a stale-lock version bump from ANY
// lane (auto-release or the manual release skill) when the mandatory pre-commit
// unit suite runs on the bumped tree.
function lockfileAgreesWithPackageJson(root) {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  return lock.version === pkg.version && lock.packages[''].version === pkg.version;
}

// (h) Absence guard for the lane retired by #266.
const RETIRED_WORKFLOW = join('.github', 'workflows', 'auto-release-on-dependency.yml');
// Bans the retired workflow's MACHINE IDENTIFIER in any case or
// hyphen/underscore variant (the realistic resurrection vector: a filename or
// file reference). Deliberately does NOT match the space-separated concept
// phrase "auto-release on dependency update", which legitimately names Lane B
// itself; prose resurrection without a mechanism is covered by the
// workflow_run prong below.
const RETIRED_LANE_PATTERN = 'auto[-_]release[-_]on[-_]dependency';
function referencesRetiredLane(text) {
  return new RegExp(RETIRED_LANE_PATTERN, 'i').test(text);
}
// git grep over TRACKED files only, scoped to the regeneration surface. Exits
// 1 when nothing matches (clean); any other failure propagates loudly.
function findRetiredLaneReferences(root) {
  try {
    const out = execFileSync('git',
      ['grep', '-lIiE', RETIRED_LANE_PATTERN, '--', '.claude', '.github'],
      { cwd: root, encoding: 'utf8' });
    return out.split('\n').filter(Boolean);
  } catch (err) {
    if (err.status === 1) return [];
    throw err;
  }
}
// Rename-proof prong: the retired lane's mechanism was a workflow_run listener
// releasing on CI/CD completion. No workflow may use that trigger, whatever
// its filename; dependency-update.yml is the only auto-release writer to main.
function workflowsUsingWorkflowRun(root) {
  const dir = join(root, '.github', 'workflows');
  return readdirSync(dir)
    .filter((f) => f.endsWith('.yml') || f.endsWith('.yaml'))
    .filter((f) => /(^|\n)\s*workflow_run\s*:/.test(readFileSync(join(dir, f), 'utf8')));
}

// (i) #297: the BUMPED tree is re-verified (build + tool-count drift guard +
// unit suite) AFTER the bump step and BEFORE the merge/tag step, so the commit
// that reaches main and gets the immutable tag is not the one commit CI skipped.
// The merge/tag step is anchored on `git tag -a` (unique to it; the sync step
// also runs `git merge --ff-only`, so merge alone is ambiguous).
function reverifiesBumpedTree(text) {
  const blocks = stepBlocks(text);
  const bumpIdx = blocks.findIndex((b) => b.includes('npm run version:bump'));
  const tagIdx = blocks.findIndex((b) => b.includes('git tag -a'));
  const reverifyIdx = blocks.findIndex((b) =>
    b.includes('npm run build') &&
    b.includes('npm run tool-count') &&
    b.includes('npm run test:unit-js') &&
    !/continue-on-error:\s*true/i.test(b));  // a neutered step must not satisfy it
  return bumpIdx !== -1 && tagIdx !== -1 && reverifyIdx !== -1 &&
    reverifyIdx > bumpIdx && reverifyIdx < tagIdx;
}

